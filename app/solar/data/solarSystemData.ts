  new Map(
    SOLAR_SYSTEM_BODIES.map((body) => [body.id, body] as const),
  );

export const PRIMARY_BODIES = SOLAR_SYSTEM_BODIES.filter(
  (body) => body.type !== "moon",
);

export const MOONS = SOLAR_SYSTEM_BODIES.filter(
  (body) => body.type === "moon",
);

export function getCelestialBody(id: string): CelestialBodyData | undefined {
  return CELESTIAL_BODY_BY_ID.get(id);
}

export function getMoonsFor(parentId: string): readonly CelestialBodyData[] {
  return MOONS.filter((moon) => moon.parentId === parentId);
}
